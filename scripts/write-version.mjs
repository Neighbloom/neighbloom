// Stamps every build with a unique id in two places:
//   - src/buildId.js      (bundled into the app: "the build I am")
//   - public/version.json (copied to dist: "the build being served")
// The app compares them at runtime; a mismatch means the browser is
// running a stale cached copy, and it offers a refresh. Runs via
// the prebuild npm hook so local, Codespace, and CI builds all stamp.
import { writeFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';

const id = `${new Date().toISOString().replace(/[^0-9]/g, '').slice(0, 14)}-${randomBytes(3).toString('hex')}`;
writeFileSync(new URL('../src/buildId.js', import.meta.url), `// Generated by scripts/write-version.mjs at build time — do not edit.\nexport const BUILD_ID = '${id}';\n`);
writeFileSync(new URL('../public/version.json', import.meta.url), JSON.stringify({ build: id }) + '\n');
console.log(`[version] stamped build ${id}`);
